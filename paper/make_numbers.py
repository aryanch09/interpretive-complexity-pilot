"""
Generate paper/numbers.tex — every figure the paper cites, as LaTeX macros read
from output/.

Project rule: no number is hand-typed into the paper. The paper says
\\PrimaryJTp, not "0.013". If a number is not in output/, the macro is emitted as
\\todo{...} so an unfilled value is loud in the PDF rather than silently stale.

Run:  python3 -m paper.make_numbers
"""
from __future__ import annotations

import json
import logging
import sys
from pathlib import Path

import pandas as pd

sys.modules.setdefault("tensorflow", None)

from config import Config

logger = logging.getLogger(__name__)

MISSING: list[str] = []


def _fmt(v, spec: str = ".3f") -> str:
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return r"\textcolor{red}{??}"
    if isinstance(v, (int,)) or (isinstance(v, float) and float(v).is_integer() and abs(v) >= 1000):
        return f"{int(v):,}"
    if isinstance(v, float):
        return format(v, spec)
    return str(v)


def _macro(name: str, value, spec: str = ".3f") -> str:
    r"""One \newcommand. A missing value becomes a visible \todo in the PDF."""
    if value is None:
        MISSING.append(name)
        return rf"\newcommand{{\{name}}}{{\todo{{{name}}}}}"
    return rf"\newcommand{{\{name}}}{{{_fmt(value, spec)}}}"


def _load_json(path: Path) -> dict | None:
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        logger.warning("could not parse %s: %s", path, exc)
        return None


def _p(v) -> str:
    """p-values: report < 0.001 rather than a misleading 0.000."""
    if v is None:
        return None
    return "<0.001" if float(v) < 0.001 else format(float(v), ".3f")


def build(config: Config) -> str:
    out = config.OUTPUT_DIR
    exp = out / "experiments"
    L: list[str] = []
    L.append("% Generated by paper/make_numbers.py — DO NOT EDIT BY HAND.")
    L.append("% Regenerate with: make numbers")
    L.append(r"\providecommand{\todo}[1]{\textcolor{red}{\textbf{[TODO: #1]}}}")
    L.append("")

    # ── Sample and extraction ────────────────────────────────────────────────
    L.append("% --- sample and extraction ---")
    ext_path = out / "extraction_report.csv"
    if ext_path.exists():
        e = pd.read_csv(ext_path)
        L.append(_macro("NFilings", len(e)))
        L.append(_macro("NFirms", e["ticker"].nunique()))
        L.append(_macro("NWindows", int(e["total_windows"].sum())))
        L.append(_macro("NCalls", int(e["total_windows"].sum()) * 3))
        L.append(_macro("NWindowsMDA", int(e["mda_windows"].sum())))
        L.append(_macro("NCallsMDA", int(e["mda_windows"].sum()) * 3))
        L.append(_macro("NFilingsWithRisk", int((e["risk_windows"] > 0).sum())))
        L.append(_macro("NFilingsNoRisk", int((e["risk_windows"] == 0).sum())))
        for tier in ("large", "mid", "small"):
            s = e[e["tier"] == tier]
            L.append(_macro(f"MdaWindowsMedian{tier.capitalize()}",
                            float(s["mda_windows"].median()), ".1f"))
        L.append(_macro("MdaWordsMin", int(e["mda_words"].min())))
        L.append(_macro("MdaWordsMax", int(e["mda_words"].max())))
    else:
        MISSING.append("extraction_report.csv")
        for n in ("NFilings", "NFirms", "NWindows", "NCalls", "NWindowsMDA",
                  "NCallsMDA", "NFilingsWithRisk", "NFilingsNoRisk"):
            L.append(_macro(n, None))
    L.append("")

    # ── Coverage confound ────────────────────────────────────────────────────
    L.append("% --- the coverage confound (retired 2,000-word cap) ---")
    cov_path = out / "coverage_diagnostic.csv"
    if cov_path.exists():
        from scipy.stats import spearmanr
        c = pd.read_csv(cov_path)
        rank = {"small": 1, "mid": 2, "large": 3}
        rho, p = spearmanr(c["tier"].map(rank), c["fraction_read_old_cap"])
        L.append(_macro("CoverageRho", float(rho)))
        L.append(_macro("CoverageP", _p(p)))
        L.append(_macro("CoverageN", len(c)))
        L.append(_macro("NTruncated", int((c["fraction_read_old_cap"] < 1.0).sum())))
        for tier in ("large", "mid", "small"):
            s = c[c["tier"] == tier]
            L.append(_macro(f"FracRead{tier.capitalize()}",
                            float(s["fraction_read_old_cap"].median()) * 100, ".1f"))
            L.append(_macro(f"SectionWords{tier.capitalize()}",
                            int(s["section_words_total"].median())))
    else:
        MISSING.append("coverage_diagnostic.csv")
        for n in ("CoverageRho", "CoverageP", "CoverageN", "NTruncated"):
            L.append(_macro(n, None))
    L.append("")

    # ── Primary result and the confirmatory test ─────────────────────────────
    L.append("% --- primary result (MD&A embedding disagreement, firm level) ---")
    bat = _load_json(exp / "window_battery" / "report.json")
    primary = (bat or {}).get("primary", {})
    for tier in ("large", "mid", "small"):
        tm = (primary.get("tier_means") or {}).get(tier)
        v = tm.get("mean") if isinstance(tm, dict) else tm
        sd = tm.get("sd") if isinstance(tm, dict) else None
        L.append(_macro(f"TierMean{tier.capitalize()}", v, ".4f"))
        L.append(_macro(f"TierSD{tier.capitalize()}", sd, ".4f"))
    L.append(_macro("PrimaryGradient", primary.get("gradient_small_minus_large"), ".4f"))
    _jt = primary.get("jonckheere_terpstra") or {}
    _lp = primary.get("label_permutation") or {}
    L.append(_macro("PrimaryJT", _jt.get("statistic"), ".1f"))
    L.append(_macro("PrimaryJTz", _jt.get("z")))
    L.append(_macro("PrimaryJTp", _p(_jt.get("p_value"))))
    L.append(_macro("PrimaryPermP", _p(_lp.get("p_value"))))
    L.append(_macro("PrimaryMonotone",
                    "yes" if primary.get("monotone_small_gt_mid_gt_large") else
                    ("no" if primary.get("monotone_small_gt_mid_gt_large") is not None else None)))
    L.append("")

    # ── Window-count battery ─────────────────────────────────────────────────
    L.append("% --- window-count battery ---")
    w3 = ((bat or {}).get("W3") or {}).get("by_k", {}).get("k=2", {})
    _g = (bat or {}).get("gate", {})
    L.append(_macro("WThreeShare", w3.get("share_primary_sign_holds"), ".3f"))
    L.append(_macro("WThreePassed",
                    "yes" if w3.get("criterion_met") else
                    ("no" if w3.get("criterion_met") is not None else None)))
    gate = (bat or {}).get("gate", {})
    L.append(_macro("GateBatteryPassed",
                    "yes" if gate.get("battery_half_of_gate_passed") else
                    ("no" if gate.get("battery_half_of_gate_passed") is not None else None)))
    w6 = (bat or {}).get("W6") or {}
    L.append(_macro("WSixPercentile", w6.get("observed_percentile_in_null"), ".1f"))
    L.append(_macro("WSixP", _p(w6.get("p_value_one_sided"))))
    L.append("")

    # ── W5 mixed model ───────────────────────────────────────────────────────
    L.append("% --- W5 mixed model ---")
    w5 = _load_json(out / "w5_mixed_model.json")
    _spec_name = (w5 or {}).get("primary_spec") or "firm_only"
    sl = ((w5 or {}).get("specs") or {}).get(_spec_name, {})
    coef = (sl.get("coefficients") or {}).get("tier_small", {})
    L.append(_macro("WFiveSpec", _spec_name.replace("_", r"\_")))
    L.append(_macro("WFiveSmallCoef", coef.get("estimate"), ".4f"))
    L.append(_macro("WFiveSmallCIlo", coef.get("ci_low"), ".4f"))
    L.append(_macro("WFiveSmallCIhi", coef.get("ci_high"), ".4f"))
    L.append(_macro("WFiveSmallP", _p(coef.get("p"))))
    _iccs = sl.get("iccs") or {}
    # The filing-level ICC exists only in the nested specification, which did not
    # converge, so it is not emitted as a citable number. Split-half reliability
    # measures the same thing by a method that does converge.
    _nested_icc = (((w5 or {}).get("specs") or {}).get("nested", {}).get("iccs") or {})
    L.append(_macro("ICCFilingNonConverged", _nested_icc.get("icc_filing"), ".3f"))
    L.append(_macro("ICCFirm", _iccs.get("icc_firm"), ".3f"))
    _vd = ((w5 or {}).get("variance_decomposition") or {}).get("raw") or {}
    _sst = _vd.get("ss_total")
    _ssw = _vd.get("ss_within_filings")
    L.append(_macro("VarWithinFiling",
                    (float(_ssw) / float(_sst)) if (_sst and _ssw) else None, ".3f"))
    L.append(_macro("VarWithinFilingPct",
                    (float(_ssw) / float(_sst) * 100) if (_sst and _ssw) else None, ".1f"))
    L.append(_macro("WFiveCriterionMet",
                    "yes" if (w5 or {}).get("criterion_met") else
                    ("no" if (w5 or {}).get("criterion_met") is not None else None)))
    L.append("")

    # ── Reliability ──────────────────────────────────────────────────────────
    L.append("% --- R1 reliability ---")
    rel = _load_json(exp / "reliability" / "results.json")
    emb = (rel or {}).get("embedding_disagreement", {})
    L.append(_macro("SplitHalfR", (emb.get("split_half") or {}).get("pearson_half_half")))
    L.append(_macro("SplitHalfSB",
                    (emb.get("split_half") or {}).get("spearman_brown_from_pearson")))
    L.append(_macro("TestRetestR", (emb.get("test_retest") or {}).get("pearson_10K_10Q")))
    L.append(_macro("TestRetestP", _p((emb.get("test_retest") or {}).get("pearson_p"))))
    L.append("")

    # ── Numeric measure and the retirement rule ──────────────────────────────
    L.append("% --- numeric measure / retirement rule ---")
    chunk_path = out / "chunk_level_results.csv"
    res_path = out / "results.csv"
    if chunk_path.exists() and res_path.exists():
        from scipy.stats import spearmanr
        ch = pd.read_csv(chunk_path)
        # MD&A windows only: the plan makes MD&A the primary section, so the
        # retirement rule is defined there, not on a pooled MD&A+Risk column.
        sub = ch[(ch.section == "mda")
                 & (~ch.any_failed.astype(str).str.lower().isin(["true", "1"]))
                 & ch.numeric_disagreement.notna()]
        fil = (sub.groupby(["ticker", "filing_type", "filing_date"])
                  .numeric_disagreement.mean().reset_index())
        rr = pd.read_csv(res_path)[["ticker", "filing_type", "filing_date", "mda_words"]]
        for f in (fil, rr):
            f["filing_date"] = f.filing_date.astype(str).str.replace("-", "", regex=False)
        r = fil.merge(rr, on=["ticker", "filing_type", "filing_date"], how="inner")
        if {"numeric_disagreement", "mda_words"}.issubset(r.columns):
            ok = r["numeric_disagreement"].notna() & r["mda_words"].notna()
            if ok.sum() >= 3:
                rho, p = spearmanr(r.loc[ok, "numeric_disagreement"],
                                   r.loc[ok, "mda_words"])
                L.append(_macro("NumericLengthRho", float(rho)))
                L.append(_macro("NumericLengthP", _p(p)))
                L.append(_macro("NumericLengthN", int(ok.sum())))
                retired = bool(rho >= 0.30 and p < 0.05)
                L.append(_macro("NumericRetired", "yes" if retired else "no"))
    else:
        MISSING.append("results_clean.csv")
        for n in ("NumericLengthRho", "NumericLengthP", "NumericLengthN", "NumericRetired"):
            L.append(_macro(n, None))
    L.append("")

    # ── S2: the confound at scale ────────────────────────────────────────────
    L.append("% --- S2 at-scale audit ---")
    sc = _load_json(exp / "scale_audit" / "results.json")
    if sc:
        L.append(_macro("ScaleNUsable", sc.get("n_usable")))
        L.append(_macro("ScaleSuccessPct",
                        (sc.get("extraction_success_rate") or 0) * 100, ".1f"))
        L.append(_macro("ScaleElasticity",
                        sc.get("elasticity_log_narrative_on_log_float"), ".4f"))
        sp = sc.get("spearman_float_vs_narrative") or {}
        L.append(_macro("ScaleRho", sp.get("rho")))
        L.append(_macro("ScaleP", _p(sp.get("p"))))
        b = sc.get("budgets") or {}
        two = b.get("2,000 words") or {}
        L.append(_macro("ScaleTruncTwoK", (two.get("share_truncated") or 0) * 100, ".1f"))
        L.append(_macro("ScaleMedianReadTwoK",
                        (two.get("median_overall") or 0) * 100, ".1f"))
        t32 = b.get("32k tokens") or {}
        L.append(_macro("ScaleTruncThirtyTwoK",
                        (t32.get("share_truncated") or 0) * 100, ".1f"))
    else:
        for n in ("ScaleNUsable", "ScaleSuccessPct", "ScaleElasticity", "ScaleRho",
                  "ScaleP", "ScaleTruncTwoK", "ScaleMedianReadTwoK",
                  "ScaleTruncThirtyTwoK"):
            L.append(_macro(n, None))
    L.append("")

    # ── E1/E2: noise floor and persona-free baseline ─────────────────────────
    L.append("% --- E1/E2 noise floor (partial: interrupted by rate limiting) ---")
    nf_csv = exp / "noise_floor" / "noise_floor.csv"
    if nf_csv.exists():
        nf = pd.read_csv(nf_csv)
        L.append(_macro("NoiseN", len(nf)))
        if len(nf):
            ratio = (nf["inter_persona_rerun"] / nf["intra_persona_mean"]).mean()
            lens = (nf["inter_persona_rerun"] - nf["persona_free_baseline"]).mean()
            L.append(_macro("NoiseRatio", float(ratio), ".2f"))
            L.append(_macro("NoiseLensEffect", float(lens), ".4f"))
            L.append(_macro("NoiseInter", float(nf["inter_persona_rerun"].mean()), ".4f"))
            L.append(_macro("NoiseIntra", float(nf["intra_persona_mean"].mean()), ".4f"))
            L.append(_macro("NoiseNeutral",
                            float(nf["persona_free_baseline"].mean()), ".4f"))
    else:
        for n in ("NoiseN", "NoiseRatio", "NoiseLensEffect"):
            L.append(_macro(n, None))
    L.append("")

    # ── S1b: exact replication of the retired cap ────────────────────────────
    L.append("% --- S1b truncation replication (the headline) ---")
    s1b = _load_json(exp / "truncation_replication" / "results.json")
    if s1b:
        t, c = s1b.get("truncated", {}), s1b.get("complete", {})
        for arm, blob in (("Trunc", t), ("Comp", c)):
            for tier in ("large", "mid", "small"):
                L.append(_macro(f"{arm}{tier.capitalize()}",
                                (blob.get("tier_means") or {}).get(tier), ".4f"))
            L.append(_macro(f"{arm}Gradient",
                            blob.get("gradient_small_minus_large"), ".4f"))
            L.append(_macro(f"{arm}P", _p(blob.get("jt_p_one_sided"))))
            L.append(_macro(f"{arm}Monotone",
                            "yes" if blob.get("monotone") else "no"))
        pdd = s1b.get("paired_delta") or {}
        L.append(_macro("PairedDelta", pdd.get("mean_truncated_minus_complete"), ".4f"))
        L.append(_macro("PairedDeltaLo", (pdd.get("ci") or [None, None])[0], ".4f"))
        L.append(_macro("PairedDeltaHi", (pdd.get("ci") or [None, None])[1], ".4f"))
        L.append(_macro("PairedDeltaN", pdd.get("n_firms")))
    L.append("")

    # ── E4/E6: placebo and familiarity ───────────────────────────────────────
    L.append("% --- E4 content placebo / E6 familiarity ---")
    pl = _load_json(exp / "placebo" / "results.json")
    if pl:
        for cond in ("real", "shuffled", "boilerplate", "anonymised"):
            v = (pl.get("conditions") or {}).get(cond)
            L.append(_macro(f"Plac{cond.capitalize()}",
                            (v or {}).get("mean"), ".4f"))
        for cond in ("shuffled", "boilerplate"):
            v = pl.get(f"real_minus_{cond}")
            if v:
                L.append(_macro(f"PlacDiff{cond.capitalize()}", v.get("mean"), ".4f"))
                L.append(_macro(f"PlacDiff{cond.capitalize()}Lo", v["ci"][0], ".4f"))
                L.append(_macro(f"PlacDiff{cond.capitalize()}Hi", v["ci"][1], ".4f"))
        L.append(_macro("PlacN", pl.get("n_windows")))
    L.append("")

    # ── F2: what the measure responds to ─────────────────────────────────────
    L.append("% --- F2 informativeness ---")
    q = _load_json(exp / "qualitative" / "results.json")
    if q:
        inf = ((q.get("F2_location") or {}).get("informativeness") or {})
        nd = inf.get("numeric_density") or {}
        L.append(_macro("NumDensityRho", nd.get("rho")))
        L.append(_macro("NumDensityP", _p(nd.get("p"))))
        bysec = ((q.get("F2_location") or {}).get("by_section") or {})
        L.append(_macro("DisagMDA", (bysec.get("mda") or {}).get("mean"), ".4f"))
        L.append(_macro("DisagRisk", (bysec.get("risk") or {}).get("mean"), ".4f"))
    L.append("")

    # ── E7: cross-model replication ──────────────────────────────────────────
    L.append("% --- E7 cross-model ---")
    e7 = _load_json(exp / "cross_model" / "results.json")
    if e7:
        L.append(_macro("CrossModel", str(e7.get("cross_model", "")).replace("_", r"\_")))
        for cond in ("real", "boilerplate"):
            v = (e7.get("conditions") or {}).get(cond)
            L.append(_macro(f"Cross{cond.capitalize()}", (v or {}).get("mean"), ".4f"))
        v = e7.get("real_minus_boilerplate")
        if v:
            L.append(_macro("CrossDiffBoiler", v.get("mean"), ".4f"))
            L.append(_macro("CrossDiffBoilerLo", v["ci"][0], ".4f"))
            L.append(_macro("CrossDiffBoilerHi", v["ci"][1], ".4f"))
        L.append(_macro("CrossInversionReplicates",
                        "yes" if e7.get("inversion_replicates") else "no"))
        L.append(_macro("CrossN", e7.get("n_windows")))
    L.append("")

    # ── Provenance ───────────────────────────────────────────────────────────
    L.append("% --- provenance ---")
    import subprocess
    try:
        h = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                           cwd=config.BASE_DIR, capture_output=True, text=True,
                           check=True).stdout.strip()
    except Exception:  # noqa: BLE001
        h = None
    L.append(_macro("GitHash", h))
    # Two hashes, not one. The plan was first committed, then amended once --
    # before any filing was scored -- to declare the score-parser correction.
    # Citing only the final hash would hide the amendment; citing only the first
    # would misidentify the version actually used.
    def _plan_hash(which: str) -> str | None:
        try:
            out = subprocess.run(
                ["git", "log", "--format=%h", "--", "ANALYSIS_PLAN.md"],
                cwd=config.BASE_DIR, capture_output=True, text=True, check=True,
            ).stdout.split()
            if not out:
                return None
            return out[0] if which == "last" else out[-1]
        except Exception:  # noqa: BLE001
            return None

    L.append(_macro("PlanHashFirst", _plan_hash("first")))
    L.append(_macro("PlanHashUsed", _plan_hash("last")))
    try:
        n_amend = len(subprocess.run(
            ["git", "log", "--format=%h", "--", "ANALYSIS_PLAN.md"],
            cwd=config.BASE_DIR, capture_output=True, text=True, check=True,
        ).stdout.split()) - 1
    except Exception:  # noqa: BLE001
        n_amend = None
    L.append(_macro("PlanAmendments", n_amend))
    L.append(_macro("ModelName", config.MODEL_NAME.replace("_", r"\_")))
    L.append(_macro("ChunkWords", config.CHUNK_WORDS))
    L.append("")

    return "\n".join(L)


def main() -> int:
    config = Config()
    text = build(config)
    dest = Path(config.BASE_DIR) / "paper" / "numbers.tex"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text + "\n", encoding="utf-8")

    n_macros = text.count(r"\newcommand")
    print(f"wrote {dest} — {n_macros} macros")
    if MISSING:
        print(f"\n{len(MISSING)} value(s) NOT YET AVAILABLE (emitted as visible \\todo):")
        for m in MISSING:
            print(f"  - {m}")
        print("\nThese fill in once the corresponding analysis has run. They are "
              "deliberately loud in the PDF rather than silently wrong.")
    return 0


if __name__ == "__main__":
    logging.basicConfig(level=logging.WARNING)
    raise SystemExit(main())
