MISSING: list[str] = []


def _load(rel: str) -> dict | None:
    p = OUT / rel
    if not p.exists():
        return None
    return json.loads(p.read_text(encoding="utf-8"))


def _get(d, *path):
    for k in path:
        if d is None:
            return None
        if isinstance(d, list):
            d = d[k] if isinstance(k, int) and k < len(d) else None
        else:
            d = d.get(k)
    return d


def _fmt(v, spec):
    if spec == "pct1":
        return f"{100 * v:.1f}"
    if spec == "int":
        return f"{int(round(v)):,}"
    if spec == "p":
        return "<0.001" if v < 0.001 else f"{v:.3f}"
    if spec.startswith("+"):
        return format(v, spec)
    return format(v, spec)


def m(name: str, value, spec: str = ".4f") -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        MISSING.append(name)
        return rf"\newcommand{{\{name}}}{{\todo{{{name}}}}}"
    return rf"\newcommand{{\{name}}}{{{_fmt(value, spec)}}}"


